<?php

namespace App\Service\Extra;

/**
 * Латинизация текста в "красивый" slug для ссылок (см. SlugTrait).
 *
 * Слаг — декоративная проекция названия, а НЕ идентификатор: сущность
 * всегда ищется по UUID, слаг нигде не хранится и не проверяется на
 * уникальность (см. докблок SlugTrait). Раньше эта же логика жила прямо в
 * Ticket::getSlug() (06.09.2026) — вынесена сюда без изменения поведения,
 * чтобы не копировать таблицу транслитерации в каждую сущность.
 *
 * Таблица покрывает русский и таджикский алфавиты (ғ ӣ қ ӯ ҳ ҷ) — все три
 * языка API (?locale=tj|ru|eng); английский текст и так латиница. Символы вне
 * таблицы и вне a-z0-9 превращаются в дефис; если ничего не осталось —
 * возвращается $fallback.
 */
final class SlugUtil
{
    private const array TRANSLIT = [
        'а'=>'a','б'=>'b','в'=>'v','г'=>'g','ғ'=>'gh','д'=>'d','е'=>'e','ё'=>'yo',
        'ж'=>'zh','з'=>'z','и'=>'i','ӣ'=>'i','й'=>'y','к'=>'k','қ'=>'q','л'=>'l',
        'м'=>'m','н'=>'n','о'=>'o','п'=>'p','р'=>'r','с'=>'s','т'=>'t','у'=>'u',
        'ӯ'=>'u','ф'=>'f','х'=>'kh','ҳ'=>'h','ц'=>'ts','ч'=>'ch','ҷ'=>'j','ш'=>'sh',
        'щ'=>'sch','ъ'=>'','ы'=>'y','ь'=>'','э'=>'e','ю'=>'yu','я'=>'ya',
    ];

    public static function make(?string $text, string $fallback): string
    {
        $latin = strtr(mb_strtolower($text ?? ''), self::TRANSLIT);
        $slug  = preg_replace('/[^a-z0-9]+/u', '-', $latin);

        return trim($slug ?? '', '-') ?: $fallback;
    }
}
